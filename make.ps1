# O Makefile para quem usa PowerShell (Windows, ou pwsh no macOS e no Linux). Os mesmos alvos,
# com os parâmetros do make virando parâmetros do script:
#
#   ./make.ps1                     menu
#   ./make.ps1 watch               dev completo com hot-reload
#   ./make.ps1 test -p Web         make test p=Web
#   ./make.ps1 logs -s app         make logs s=app
#   ./make.ps1 mock -videos 10 -collections 5.3-10
#   ./make.ps1 whisper -m base
#
# No Windows, se a política de execução bloquear o script:
#   pwsh -ExecutionPolicy Bypass -File .\make.ps1 watch
#
# Precisa do PowerShell 7 (pwsh): o 'watch' encerra a árvore de processos do dotnet watch.

#Requires -Version 7.2

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string] $Target = 'help',

    # Serviço do docker compose (restart, logs, shell).
    [string] $s,

    # Projeto de testes: Domain, Infrastructure, Worker ou Web.
    [string] $p,

    # Catálogo de exemplo do 'mock'.
    [string] $videos,
    [string] $collections,
    [string] $colections,

    # Modelo do 'whisper'.
    [string] $m
)

$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$DevDeps       = @('postgres', 'minio', 'mailpit')
$ComposeDev    = @('-f', 'docker-compose.yml', '-f', 'docker-compose.dev.yml')
$TestArtifacts = '.artifacts/test'

# ── Utilitários ───────────────────────────────────────────────────────────────

# Roda um programa e para o script se ele falhar, como o make faz com cada linha.
function Invoke-Checked {
    param([string] $Program, [string[]] $Arguments)

    & $Program @Arguments
    if ($LASTEXITCODE -ne 0) {
        exit $LASTEXITCODE
    }
}

function Test-Command([string] $Name) {
    [bool](Get-Command $Name -ErrorAction SilentlyContinue)
}

function Fail([string] $Message) {
    Write-Host "  $Message" -ForegroundColor Red
    exit 1
}

# Segredo aleatório só com letras e dígitos, como o gen-env.sh.
function New-Secret([int] $Length) {
    $alfabeto = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
    $bytes = [System.Security.Cryptography.RandomNumberGenerator]::GetBytes($Length)
    -join ($bytes | ForEach-Object { $alfabeto[$_ % $alfabeto.Length] })
}

function New-Hex([int] $Bytes) {
    [Convert]::ToHexString([System.Security.Cryptography.RandomNumberGenerator]::GetBytes($Bytes)).ToLowerInvariant()
}

