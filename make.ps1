# O .env com usuário, senha e chaves aleatórios. Se já existe, fica como está: o PostgreSQL só
# aceita a senha da primeira inicialização do volume.
function Initialize-Env {
    $destino = Join-Path $PSScriptRoot '.env'

    if (Test-Path $destino) {
        return
    }

    $admin = if ($env:OPENTUBE_ADMIN_EMAIL) { $env:OPENTUBE_ADMIN_EMAIL } else { 'admin@localhost' }

    $conteudo = @(
        '# Generated by make.ps1. Do not commit.'
        "POSTGRES_DB=db_$(New-Hex 5)"
        "POSTGRES_USER=user_$(New-Hex 4)"
        "POSTGRES_PASSWORD=$(New-Secret 32)"
        "MINIO_ROOT_USER=minio_$(New-Hex 4)"
        "MINIO_ROOT_PASSWORD=$(New-Secret 32)"
        "TOKEN_PEPPER=$(New-Secret 48)"
        "IP_HASH_PEPPER=$(New-Secret 48)"
        'OPENTUBE_HOST=localhost'
        "OPENTUBE_ADMIN_EMAIL=$admin"
    )

    # Sem BOM e com LF: o docker compose lê o mesmo arquivo.
    [System.IO.File]::WriteAllText($destino, ($conteudo -join "`n") + "`n")

    # Só para quem o criou, como o modo 600 do gen-env.sh.
    if ($IsWindows) {
        & icacls $destino /inheritance:r /grant:r "$($env:USERNAME):(R,W)" | Out-Null
    } else {
        & chmod 600 $destino
    }

    Write-Host '  .env created with a random user, password, and keys.'
    Write-Host '  The file stays on this machine only. It is not printed again.'
}

# Lê o .env e define as variáveis que a aplicação lê no host, como o scripts/dev-env.sh.
function Import-DevEnv {
    if (-not (Test-Path .env)) {
        Fail 'Missing .env. Run ./make.ps1 deps-up.'
    }

    $valores = @{}
    foreach ($linha in Get-Content .env) {
        if ($linha -match '^\s*(#|$)') { continue }
        if ($linha -notmatch '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$') { continue }

        $valor = $Matches[2].Trim()
        if ($valor -match '^"(.*)"$' -or $valor -match "^'(.*)'$") {
            $valor = $Matches[1]
        }

        $valores[$Matches[1]] = $valor
        Set-Item "env:$($Matches[1])" $valor
    }

    $conexao = "Host=localhost;Port=5432;Database=$($valores.POSTGRES_DB);Username=$($valores.POSTGRES_USER);Password=$($valores.POSTGRES_PASSWORD)"

    $env:ConnectionStrings__Default = $conexao
    $env:OPENTUBE_DB                = $conexao
    $env:Storage__Endpoint          = 'http://localhost:9000'
    $env:Storage__AccessKey         = $valores.MINIO_ROOT_USER
    $env:Storage__SecretKey         = $valores.MINIO_ROOT_PASSWORD
    $env:Security__TokenPepper      = $valores.TOKEN_PEPPER
    $env:Security__IpHashPepper     = $valores.IP_HASH_PEPPER
    $env:Security__PublicUrl        = 'http://localhost:5080'
    # O administrador do desenvolvimento vem do .env de cada máquina, e não de um arquivo do
    # repositório: o appsettings.Development.json vai dentro da imagem publicada.
    $env:Security__AdminEmails__0   = if ($valores.OPENTUBE_ADMIN_EMAIL) { $valores.OPENTUBE_ADMIN_EMAIL } else { 'admin@localhost' }
    if (-not $env:ASPNETCORE_ENVIRONMENT) { $env:ASPNETCORE_ENVIRONMENT = 'Development' }
    if (-not $env:DOTNET_ENVIRONMENT)     { $env:DOTNET_ENVIRONMENT     = 'Development' }

    # Transcrição automática de legendas: ligada quando o whisper-cli e o modelo baixado pelo
    # 'whisper' existem. Uma configuração já definida no ambiente prevalece.
    if (-not $env:Transcription__Executable -and (Test-Command whisper-cli) -and (Test-Path .whisper/modelo.bin)) {
        $env:Transcription__Executable = (Get-Command whisper-cli).Source
        $env:Transcription__ModelPath   = Join-Path $PSScriptRoot '.whisper/modelo.bin'
    }
}

# Docker no ar; no macOS, sobe o Colima se ele existir.
function Assert-Docker {
    if (-not (Test-Command docker)) {
        Fail 'Docker não encontrado no PATH. Instale o Docker Desktop (ou o Colima, no macOS).'
    }

    & docker info *> $null
    if ($LASTEXITCODE -eq 0) {
        return
    }

    if (Test-Command colima) {
        Write-Host '  Docker não está rodando. Iniciando Colima...'
        Invoke-Checked colima @('start')
        return
    }

    Fail 'Docker daemon não está rodando. Inicie o Docker Desktop ou o Colima antes de continuar.'
}

# ── Alvos ─────────────────────────────────────────────────────────────────────

$Alvos = [ordered]@{}

function Add-Target([string] $Name, [string] $Help, [scriptblock] $Action) {
    $Alvos[$Name] = [pscustomobject]@{ Help = $Help; Action = $Action }
}

Add-Target help 'Mostra este menu' {
    foreach ($nome in $Alvos.Keys) {
        Write-Host ('  {0,-16}' -f $nome) -ForegroundColor Cyan -NoNewline
        Write-Host $Alvos[$nome].Help
    }
}

