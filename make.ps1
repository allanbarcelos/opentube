# ── Dev local com hot-reload ───────────────────────────────────────────────────
# Só as dependências rodam em container. A aplicação e o worker rodam no host com as
# credenciais do .env — nunca com usuário ou senha fixos no código.
Add-Target deps-up 'Sobe só banco, storage e Mailpit, com portas no host' {
    Initialize-Env; Assert-Docker
    Invoke-Checked docker (@('compose') + $ComposeDev + @('up', '-d') + $DevDeps)
}

Add-Target deps-down 'Para as dependências de dev' {
    Invoke-Checked docker (@('compose') + $ComposeDev + @('stop') + $DevDeps)
}

Add-Target watch-web 'Só a aplicação local em hot-reload (porta 5080)' {
    Initialize-Env; Import-DevEnv
    Invoke-Checked dotnet @('watch', 'run', '--project', 'src/OpenTube.Web')
}

Add-Target watch-worker 'Só o worker local em hot-reload' {
    Initialize-Env; Import-DevEnv
    Invoke-Checked dotnet @('watch', 'run', '--project', 'src/OpenTube.Worker')
}

Add-Target watch 'Dev completo: deps em container + aplicação e worker no host' {
    Initialize-Env; Assert-Docker
    Invoke-Checked docker (@('compose') + $ComposeDev + @('up', '-d') + $DevDeps)
    Import-DevEnv

    Write-Host ''
    Write-Host '  Aplicação →  http://localhost:5080   (dotnet watch)'
    Write-Host '  Worker    →  processo local'
    Write-Host '  Banco     →  localhost:5432   usuário e senha no .env'
    Write-Host '  MinIO     →  http://localhost:9000   console :9001   credenciais no .env'
    Write-Host '  Mailpit   →  http://localhost:8025'
    if ($env:Transcription__Executable) {
        $modelo = (Get-Item .whisper/modelo.bin).Target
        Write-Host "  Legendas  →  transcrição com Whisper$(if ($modelo) { ", modelo $modelo" })"
    } else {
        Write-Host "  Legendas  →  transcrição desligada ('./make.ps1 whisper' instala o Whisper e o modelo)"
    }
    Write-Host "  Ctrl+C encerra aplicação e worker. As deps seguem ('./make.ps1 deps-down' para pará-las)."
    Write-Host ''

    # Os dois no mesmo console, herdando as variáveis do .env. Ao sair, por Ctrl+C ou porque um
    # deles terminou, a árvore inteira de cada um é encerrada: o dotnet watch deixa filhos.
    $processos = @(
        Start-Process dotnet -ArgumentList 'watch', 'run', '--project', 'src/OpenTube.Web' -NoNewWindow -PassThru
        Start-Process dotnet -ArgumentList 'watch', 'run', '--project', 'src/OpenTube.Worker' -NoNewWindow -PassThru
    )

    try {
        while (-not ($processos | Where-Object HasExited)) {
            Start-Sleep -Milliseconds 500
        }
    } finally {
        foreach ($processo in $processos) {
            if (-not $processo.HasExited) {
                $processo.Kill($true)
            }
        }
    }
}

# Grava um catálogo de exemplo no banco do 'watch'. Sem argumento: 5 vídeos soltos e 5 coleções
# com 3 vídeos. -videos N muda os soltos. -collections N.M-K gera N coleções, cada uma com M a K
# vídeos. Compila em .artifacts/mock para não disputar bin/obj com o 'watch'. Rodar de novo
# substitui só os slugs que começam com mock-.
Add-Target mock 'Gera coleções e vídeos de teste  →  ./make.ps1 mock -videos 10 -collections 5.3-10' {
    Initialize-Env; Assert-Docker
    Invoke-Checked docker (@('compose') + $ComposeDev + @('up', '-d', '--wait') + $DevDeps)

    if (-not (Test-Command ffmpeg))  { Fail 'ffmpeg não está no PATH. Instale o FFmpeg antes do mock.' }
    if (-not (Test-Command ffprobe)) { Fail 'ffprobe não está no PATH. Ele acompanha o FFmpeg.' }

    Import-DevEnv

    $argumentos = @('run', '--project', 'src/OpenTube.Mock', '--artifacts-path', '.artifacts/mock', '--')
    if ($videos)      { $argumentos += @('--videos', $videos) }
    if ($collections) { $argumentos += @('--collections', $collections) }
    if ($colections)  { $argumentos += @('--collections', $colections) }

    Invoke-Checked dotnet $argumentos
}

# Instala o whisper.cpp e baixa o modelo usado pelo worker do 'watch', conferindo o SHA-256
# publicado. O modelo pode ser trocado: -m base (rápido) | small (melhor) |
# large-v3-turbo-q5_0 (o mais preciso).
Add-Target whisper "Liga a transcrição de legendas no watch  →  ./make.ps1 whisper -m base" {
    $modelo = if ($m) { $m } else { 'small-q5_1' }
    $origem = 'https://huggingface.co/ggerganov/whisper.cpp/resolve/main'

    # A mesma tabela que a imagem de produção usa. Um modelo fora dela é recusado: baixar sem
    # conferir seria aceitar qualquer arquivo com esse nome.
    $tabela = Get-Content docker/whisper/modelos.txt | Where-Object { $_ -notmatch '^\s*(#|$)' } |
        ForEach-Object { $c = -split $_; [pscustomobject]@{ Nome = $c[0]; Sha = $c[1] } }
    $sha = ($tabela | Where-Object Nome -eq $modelo).Sha

    if (-not $sha) {
        Fail "Modelo desconhecido: $modelo. Use um destes: $($tabela.Nome -join ' ')"
    }

    # ── Programa
    if (Test-Command whisper-cli) {
        Write-Host "  whisper-cli já instalado: $((Get-Command whisper-cli).Source)"
    } elseif (Test-Command brew) {
        Write-Host '  Instalando o whisper.cpp pelo Homebrew...'
        Invoke-Checked brew @('install', 'whisper-cpp')
    } else {
        Fail 'O whisper-cli não foi encontrado. Instale o whisper.cpp (https://github.com/ggml-org/whisper.cpp), ponha o whisper-cli no PATH e rode de novo.'
    }

    # ── Modelo
    New-Item -ItemType Directory -Force .whisper | Out-Null
    $arquivo = ".whisper/ggml-$modelo.bin"
    $confere = { param($caminho) (Test-Path $caminho) -and (Get-FileHash $caminho -Algorithm SHA256).Hash -eq $sha.ToUpperInvariant() }

    if (& $confere $arquivo) {
        Write-Host "  Modelo $modelo já baixado e conferido"
    } else {
        Write-Host "  Baixando o modelo $modelo..."
        $parcial = "$arquivo.parcial"
        Invoke-WebRequest "$origem/ggml-$modelo.bin" -OutFile $parcial -MaximumRetryCount 3

        if (-not (& $confere $parcial)) {
            Remove-Item $parcial -Force
            Fail 'O arquivo baixado não confere com o SHA-256 publicado; nada foi instalado.'
        }

        Move-Item $parcial $arquivo -Force
        Write-Host "  Modelo conferido: $arquivo"
    }

    # O modelo em uso tem um nome fixo, para o Import-DevEnv não precisar saber qual foi
    # escolhido. Link simbólico onde der; no Windows sem permissão para isso, um hard link.
    Remove-Item .whisper/modelo.bin -Force -ErrorAction SilentlyContinue
    try {
        New-Item -ItemType SymbolicLink -Path .whisper/modelo.bin -Target "ggml-$modelo.bin" | Out-Null
    } catch {
        New-Item -ItemType HardLink -Path .whisper/modelo.bin -Target $arquivo | Out-Null
    }

    Write-Host ''
    Write-Host "  Transcrição pronta com o modelo $modelo. Reinicie o './make.ps1 watch' para o worker usá-la."
}

