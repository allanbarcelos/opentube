# ── Tests ─────────────────────────────────────────────────────────────────────
# Os testes de integração sobem Postgres e MinIO próprios (Testcontainers): precisam do Docker,
# mas não do .env nem das dependências do 'watch'. Os que usam FFmpeg são pulados quando ele não
# está instalado. Compilam em .artifacts/test, e não no bin/obj dos projetos, para não disputar
# arquivos com o 'watch' aberto.
Add-Target test 'Roda os testes  →  ./make.ps1 test  |  ./make.ps1 test -p Web  (Domain, Infrastructure, Worker, Web)' {
    Assert-Docker
    $alvo = if ($p) { "tests/OpenTube.$p.Tests" } else { 'OpenTube.slnx' }
    Invoke-Checked dotnet @('test', $alvo, '--artifacts-path', $TestArtifacts)
}

# ── License headers ───────────────────────────────────────────────────────────
# Todo arquivo de código leva o cabeçalho SPDX com licença e autoria; o CI recusa o que faltar.
Add-Target headers 'Acrescenta o cabeçalho de licença e autoria onde faltar (o CI confere)' {
    $python = @('python3', 'python', 'py') | Where-Object { Test-Command $_ } | Select-Object -First 1
    if (-not $python) {
        Fail 'Python 3 não encontrado no PATH.'
    }

    Invoke-Checked $python @('scripts/license-headers.py')
}

# ── Maintenance ───────────────────────────────────────────────────────────────
Add-Target clean 'Remove containers, volumes e orphans  (reset completo)' {
    Invoke-Checked docker @('compose', 'down', '-v', '--remove-orphans')
}

Add-Target shell 'Abre shell em um container em execução  →  ./make.ps1 shell -s app' {
    if (-not $s) {
        Fail 'Informe o serviço: ./make.ps1 shell -s app'
    }

    Invoke-Checked docker @('compose', 'exec', $s, 'sh')
}

# ── Execução ──────────────────────────────────────────────────────────────────
