    public static string Get(string english)
    {
        var idioma = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;

        if (idioma == "pt" && Portugues.TryGetValue(english, out var pt))
            return pt;

        if (idioma == "fr" && Frances.TryGetValue(english, out var fr))
            return fr;

        return english;
    }

    public static string Format(string english, params object?[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(english), args);

